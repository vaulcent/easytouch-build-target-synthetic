"""Automation: create exactly one Project for every submitted Sales Invoice.

Hooked via ``doc_events`` -> Sales Invoice -> ``on_submit`` in hooks.py.

The handler is intentionally idempotent: the Project name is deterministically
derived from the invoice's customer and invoice number, and Project.name is
unique, so re-running the handler for the same submitted Sales Invoice (e.g.
on an event retry) never creates a duplicate Project.
"""

import frappe


def get_project_name_for_invoice(sales_invoice_doc):
    """Build the deterministic Project name for a Sales Invoice.

    Uses the customer (display name when available, else the Customer id)
    and the Sales Invoice number so the same submitted invoice always maps
    to the same Project name.
    """
    customer_label = getattr(sales_invoice_doc, "customer_name", None) or sales_invoice_doc.customer
    return f"{customer_label} - {sales_invoice_doc.name}"


def create_project_for_submitted_sales_invoice(doc, method=None):
    """Sales Invoice ``on_submit`` hook: create one linked Project.

    Idempotent: if a Project with the deterministic name already exists
    (e.g. because this handler already ran for this invoice, or the
    submit event is retried/replayed), no new Project is created.
    """
    if doc.docstatus != 1:
        # Defensive guard: only act on actually-submitted invoices even if
        # this handler is ever invoked outside the on_submit hook context.
        return None

    project_name = get_project_name_for_invoice(doc)

    if frappe.db.exists("Project", project_name):
        return frappe.db.get_value("Project", project_name, "name")

    project = frappe.get_doc(
        {
            "doctype": "Project",
            "project_name": project_name,
            # Project.company is mandatory in ERPNext v16; derive it from
            # the originating Sales Invoice so the created Project is
            # correctly scoped to the same Company as its source document.
            "company": doc.company,
        }
    )
    try:
        # ``set_name`` forces Project.name (the primary key) to be the
        # exact deterministic string built from the customer and invoice
        # number, regardless of the Project doctype's own autoname rule
        # (e.g. a naming series). Without this, the stored Project could
        # end up with an autogenerated name that never matches the
        # deterministic name this automation (and its idempotency check)
        # relies on.
        project.insert(ignore_permissions=True, set_name=project_name)
    except frappe.DuplicateEntryError:
        # Another process/retry created it first: idempotently reuse it.
        return frappe.db.get_value("Project", project_name, "name")
    return project.name
